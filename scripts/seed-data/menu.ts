/**
 * Меню клуба — раздел 4 res-transcription.md (страницы 1–19), построчно.
 *
 * Правила:
 * - выход/объём — в единицах источника (мл не пересчитываются в литры);
 * - нет выхода/объёма в источнике → вариант только с ценой (amount/unit = null);
 * - выбор без смены цены → choiceNote, название позиции — без опций;
 * - категории с общей сеткой цен (priceGroup) → позиции без вариантов;
 * - «Скидка 10% на вынос»: true у категорий 1–12, false у 13–16 (допущение).
 */
import type { SeedCategory, SeedItem, SeedPriceGroup, Unit } from "./types";

type Extra = Omit<SeedItem, "name" | "price" | "amount" | "unit" | "variants">;

/** Позиция с выходом/объёмом */
const sized =
  (unit: Unit) =>
  (name: string, amount: number, price: number, extra: Extra = {}): SeedItem => ({
    name,
    amount,
    unit,
    price,
    ...extra,
  });

const g = sized("g");
const ml = sized("ml");
const l = sized("l");
const pcs = sized("pcs");

/** Позиция без выхода/объёма — только цена */
const p = (name: string, price: number, extra: Extra = {}): SeedItem => ({ name, price, ...extra });

/** Позиция в категории с общей сеткой цен — без собственных цен */
const n = (name: string, extra: Extra = {}): SeedItem => ({ name, ...extra });

/** Подкатегория: slug = `${parentSlug}-${suffix}`, флаг скидки на вынос наследуется */
